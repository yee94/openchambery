export const SUPPORTED_MENU_LOCALES = [
  'en',
  'fr',
  'zh-CN',
  'zh-TW',
  'uk',
  'es',
  'pt-BR',
  'ko',
  'pl',
  'ja',
];

export const DEFAULT_MENU_LOCALE = 'en';

const matchSupportedLocale = (value) => {
  if (!value) return undefined;

  const normalized = String(value).toLowerCase().replace(/_/g, '-');
  if (
    normalized === 'zh-tw'
    || normalized.startsWith('zh-tw-')
    || normalized === 'zh-hk'
    || normalized.startsWith('zh-hk-')
    || normalized === 'zh-mo'
    || normalized.startsWith('zh-mo-')
    || normalized === 'zh-hant'
    || normalized.startsWith('zh-hant-')
  ) {
    return 'zh-TW';
  }
  if (normalized.startsWith('zh')) return 'zh-CN';
  if (normalized.startsWith('en')) return 'en';
  if (normalized === 'fr' || normalized.startsWith('fr-')) return 'fr';
  if (normalized === 'uk' || normalized.startsWith('uk-') || normalized === 'ua' || normalized.startsWith('ua-')) {
    return 'uk';
  }
  if (normalized === 'es' || normalized.startsWith('es-')) return 'es';
  if (normalized === 'pt' || normalized.startsWith('pt-')) return 'pt-BR';
  if (normalized === 'ko' || normalized.startsWith('ko-')) return 'ko';
  if (normalized === 'ja' || normalized.startsWith('ja-')) return 'ja';
  if (normalized === 'pl' || normalized.startsWith('pl-')) return 'pl';
  return undefined;
};

/** @param {string | undefined | null} value */
export const normalizeMenuLocale = (value) => matchSupportedLocale(value) ?? DEFAULT_MENU_LOCALE;

